#include "calc.h"

double calcSum(double num1, double num2){
    return (num1 + num2);
}
double calcSub(double num1, double num2){
    return (num1 - num2);
}
double calcMul(double num1, double num2){
    return (num1 * num2);
}
double calcDiv(double num1, double num2){
    return (num1 / num2);
}
double calcExp(double num1){
    return (exp(num1));
}
double calcRoot(double num1){
    return (sqrt(num1));
}